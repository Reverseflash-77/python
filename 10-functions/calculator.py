def add(a,b):
    answer = a+b
    return answer
def subtract(a,b):
    answer = a-b
    return answer
def multiply(a,b):
    answer = a*b
    return answer
def divide(a,b):
    answer = a/b
    return answer
def exp(a,b):
    answer = a**b
    return answer

print(add(6,3))
print(subtract(6,3))
print(multiply(6,3))
print(divide(6,3))
print(exp(6,3))